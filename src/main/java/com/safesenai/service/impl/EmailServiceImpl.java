package com.safesenai.service.impl;

import com.safesenai.dto.DispatchedEmail;
import com.safesenai.service.EmailService;
import jakarta.mail.internet.InternetAddress;
import jakarta.mail.internet.MimeMessage;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.mail.javamail.JavaMailSender;
import org.springframework.mail.javamail.JavaMailSenderImpl;
import org.springframework.mail.javamail.MimeMessageHelper;
import org.springframework.stereotype.Service;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.*;

@Service
public class EmailServiceImpl implements EmailService {

    private static final Logger log = LoggerFactory.getLogger(EmailServiceImpl.class);
    private final List<String> emailAuditLogs = Collections.synchronizedList(new ArrayList<>());
    private final List<DispatchedEmail> dispatchedPreviews = Collections.synchronizedList(new ArrayList<>());

    @Autowired(required = false)
    private JavaMailSender mailSender;

    @Value("${spring.mail.username:suthanthadeus2006@gmail.com}")
    private String fromEmail;

    @Value("${spring.mail.password:}")
    private String mailPassword;

    @Override
    public boolean sendDistressEmail(String recipientEmail, String subject, String commuterName, String mapsUrl, double lat, double lon) {
        String timestamp = LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss"));
        String googleMapsUrl = String.format(Locale.US, "https://www.google.com/maps?q=%.6f,%.6f", lat, lon);
        String osmUrl = String.format(Locale.US, "https://www.openstreetmap.org/?mlat=%.6f&mlon=%.6f#map=17/%.6f/%.6f", lat, lon, lat, lon);

        String entry = String.format("[%s] DISPATCHING URGENT EMAIL TO %s (User: %s | Lat: %.6f, Lon: %.6f)",
                timestamp, recipientEmail, commuterName, lat, lon);

        log.warn("=== SMTP DISTRESS EMAIL OUTBOUND ===");
        log.warn(entry);

        String htmlContent = "<div style='font-family: -apple-system, BlinkMacSystemFont, Segoe UI, Roboto, Helvetica, Arial, sans-serif; background-color: #fef2f2; border: 2px solid #ef4444; border-radius: 12px; padding: 24px; max-width: 620px; margin: 0 auto; box-shadow: 0 4px 15px rgba(239, 68, 68, 0.15);'>"
                + "<div style='text-align: center; border-bottom: 2px solid #fee2e2; padding-bottom: 16px; margin-bottom: 16px;'>"
                + "<h2 style='color: #dc2626; margin: 0; font-size: 24px; font-weight: 800; text-transform: uppercase; letter-spacing: 0.5px;'>🚨 URGENT EMERGENCY SOS ALERT</h2>"
                + "<p style='color: #7f1d1d; margin: 6px 0 0; font-size: 14px; font-weight: 600;'>SafeSen-AI Women Safety Analytics · Immediate Emergency Response</p>"
                + "</div>"
                + "<div style='background-color: #ffffff; border-radius: 8px; padding: 18px; border: 1px solid #fecaca; margin-bottom: 20px;'>"
                + "<p style='margin: 0 0 10px; font-size: 16px; color: #1e293b;'><strong>Commuter in Distress:</strong> <span style='color: #dc2626; font-weight: 800; font-size: 18px;'>" + commuterName + "</span></p>"
                + "<p style='margin: 0 0 10px; font-size: 14px; color: #475569;'><strong>Incident Timestamp:</strong> " + timestamp + "</p>"
                + "<p style='margin: 0 0 10px; font-size: 14px; color: #475569;'><strong>GPS Coordinates:</strong> <span style='font-family: monospace; background: #f1f5f9; padding: 3px 8px; border-radius: 4px; font-weight: bold;'>" + String.format("%.6f, %.6f", lat, lon) + "</span></p>"
                + "<p style='margin: 0; font-size: 14px; color: #475569;'><strong>Urgency Level:</strong> <span style='background-color: #ef4444; color: #fff; padding: 3px 10px; border-radius: 4px; font-weight: bold; font-size: 12px;'>HIGH PRIORITY (CRITICAL)</span></p>"
                + "</div>"
                + "<div style='text-align: center; margin: 24px 0;'>"
                + "<a href='" + googleMapsUrl + "' target='_blank' style='background: #ea4335; color: #ffffff; text-decoration: none; padding: 14px 28px; border-radius: 50px; font-weight: bold; font-size: 16px; display: inline-block; margin-bottom: 12px; box-shadow: 0 4px 12px rgba(234, 67, 53, 0.4);'>📍 Open Live Location in Google Maps</a><br/>"
                + "<a href='" + osmUrl + "' target='_blank' style='background: #0f172a; color: #ffffff; text-decoration: none; padding: 10px 22px; border-radius: 50px; font-size: 13px; display: inline-block;'>🗺️ Open in OpenStreetMap</a>"
                + "</div>"
                + "<p style='font-size: 13px; color: #64748b; line-height: 1.5; margin-bottom: 8px; text-align: center;'>This distress notification was automatically generated by <strong>SafeSen-AI</strong> on behalf of " + commuterName + " and dispatched simultaneously to all verified emergency contacts.</p>"
                + "<div style='text-align: center; border-top: 1px solid #fee2e2; padding-top: 12px; margin-top: 16px;'>"
                + "<span style='font-size: 12px; color: #94a3b8;'>Department of Computer Science & Engineering · V.S.B. Engineering College, Karur</span>"
                + "</div>"
                + "</div>";

        String deliveryStatus;
        boolean success = false;

        String cleanPassword = (mailPassword != null) ? mailPassword.replaceAll("\\s+", "") : "";

        if (mailSender != null && !cleanPassword.isBlank()) {
            try {
                // Ensure JavaMailSender has stripped password without whitespace
                if (mailSender instanceof JavaMailSenderImpl jms) {
                    jms.setPassword(cleanPassword);
                    if (fromEmail != null && !fromEmail.isBlank()) {
                        jms.setUsername(fromEmail.trim());
                    }
                }

                MimeMessage message = mailSender.createMimeMessage();
                MimeMessageHelper helper = new MimeMessageHelper(message, true, "UTF-8");
                helper.setFrom(new InternetAddress(fromEmail.trim(), "SafeSen-AI Women Safety"));
                helper.setTo(recipientEmail.trim());
                helper.setSubject("🚨 URGENT DISTRESS ALERT: " + commuterName + " needs immediate help!");
                helper.setText(htmlContent, true);

                mailSender.send(message);
                success = true;
                deliveryStatus = "DELIVERED via Live Gmail SMTP Server (Status: 250 OK)";
                log.info("Live Gmail SMTP email sent successfully to {}", recipientEmail);
                emailAuditLogs.add(0, String.format("[%s] ✅ LIVE SMTP SENT TO %s", timestamp, recipientEmail));
            } catch (Exception ex) {
                log.error("Live SMTP transmission failed to {}: {}", recipientEmail, ex.getMessage());
                deliveryStatus = "FAILED (SMTP Error: " + ex.getMessage() + ")";
                emailAuditLogs.add(0, String.format("[%s] ❌ SMTP ERROR (%s): %s", timestamp, recipientEmail, ex.getMessage()));
            }
        } else {
            deliveryStatus = "DELIVERED (Multi-Channel Dispatch Simulator)";
            emailAuditLogs.add(0, String.format("[%s] ℹ️ SIMULATED DISPATCH TO %s", timestamp, recipientEmail));
        }

        if (emailAuditLogs.size() > 50) {
            emailAuditLogs.remove(emailAuditLogs.size() - 1);
        }

        DispatchedEmail dispatched = new DispatchedEmail(
                recipientEmail,
                subject != null ? subject : "🚨 URGENT DISTRESS ALERT: " + commuterName,
                commuterName,
                googleMapsUrl,
                lat,
                lon,
                timestamp,
                htmlContent,
                deliveryStatus
        );
        dispatchedPreviews.add(0, dispatched);
        if (dispatchedPreviews.size() > 50) {
            dispatchedPreviews.remove(dispatchedPreviews.size() - 1);
        }

        return success;
    }

    @Override
    public List<String> getRecentEmailAuditLogs() {
        return new ArrayList<>(emailAuditLogs);
    }

    @Override
    public List<DispatchedEmail> getDispatchedEmailPreviews() {
        return new ArrayList<>(dispatchedPreviews);
    }

    @Override
    public Optional<DispatchedEmail> getLatestDispatchedEmail() {
        if (dispatchedPreviews.isEmpty()) return Optional.empty();
        return Optional.of(dispatchedPreviews.get(0));
    }
}
